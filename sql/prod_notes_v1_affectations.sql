INSERT IGNORE INTO dd_personnages_notes (pno_no_id, pno_pe_id, pno_date, pno_lu_date)
SELECT n.no_id, p.pe_id, NOW(), NOW()
  FROM tmp_affectations_v1 t
  JOIN dd_v1_notes v              ON v.no_id = t.v1_no_id
  JOIN dd_notes n                 ON n.no_id = v.no_importe_no_id AND n.no_supprime = 0
  JOIN dd_personnages p           ON p.pe_nom = t.pe_nom
  JOIN dd_campagnes_personnages c ON c.cp_pe_id = p.pe_id AND c.cp_camp_id = n.no_camp_id;

COMMIT;

DROP TEMPORARY TABLE tmp_affectations_v1;

-- Contrôle : notes reçues par personnage
SELECT p.pe_nom, COUNT(*) AS nb_notes, COUNT(pno.pno_lu_date) AS nb_lues
  FROM dd_personnages_notes pno
  JOIN dd_personnages p ON p.pe_id = pno.pno_pe_id
 GROUP BY p.pe_id, p.pe_nom
 ORDER BY p.pe_nom;
